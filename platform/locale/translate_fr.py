def french_typography(text: str) -> str:
    """Espaces insécables : le guillemet ou les deux-points ne passent jamais seuls à la ligne."""
    nbsp = "\u00a0"
    return text.replace("« ", "«" + nbsp).replace(" »", nbsp + "»").replace(" :", nbsp + ":").replace(" ;", nbsp + ";")


def po_escape(text: str) -> str:
    text = french_typography(text)
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def unescape(chunks: str) -> str:
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', chunks)
    return "".join(parts).replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def main() -> int:
    content = PO.read_text(encoding="utf-8")
    content = content.replace('"Language: \\n"', '"Language: fr\\n"')
    content = content.replace('"Project-Id-Version: PACKAGE VERSION\\n"', '"Project-Id-Version: SYSTEM-C Platform\\n"')
    content = content.replace('"Language-Team: LANGUAGE <LL@li.org>\\n"', '"Language-Team: SYSTEM-C\\n"')
    content = re.sub(r'^"Plural-Forms: [^"]*"', lambda m: '"Plural-Forms: nplurals=2; plural=(n > 1);\\n"', content, count=1, flags=re.M)
    blocks = content.split("\n\n")
    missing = []
    out = []
    for block in blocks:
        match = re.search(r'^msgid ((?:"(?:[^"\\]|\\.)*"\n?)+)', block, re.M)
        if not match:
            out.append(block)
            continue
        msgid = unescape(match.group(1))
        if not msgid:
            out.append(block)
            continue
        lines = [line for line in block.split("\n") if not line.startswith("#, fuzzy") and not line.startswith("#| ")]
        block = "\n".join(lines)
        translation = T.get(msgid)
        if translation is None:
            missing.append(msgid)
            out.append(block)
            continue
        head = block.split("\nmsgstr")[0]
        if "msgid_plural" in block:
            singular, plural = translation if isinstance(translation, tuple) else (translation, translation)
            block = f'{head}\nmsgstr[0] "{po_escape(singular)}"\nmsgstr[1] "{po_escape(plural)}"'
        else:
            text = translation[0] if isinstance(translation, tuple) else translation
            block = f'{head}\nmsgstr "{po_escape(text)}"'
        out.append(block)
    PO.write_text("\n\n".join(out), encoding="utf-8")
    if missing:
        print("Chaînes sans traduction :", *missing, sep="\n  ")
        return 1
    print("Toutes les chaînes ont une traduction.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
